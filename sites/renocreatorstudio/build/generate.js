const STATUS_LABEL = { live: 'Live', 'in-progress': 'In progress', planned: 'Planned' };

const badge = p => p.status && STATUS_LABEL[p.status]
  ? `<span class="status" data-status="${p.status}">${STATUS_LABEL[p.status]}</span>` : '';

/* The 16:10 preview panel, drawn entirely in CSS. Layout varies by discipline
   so a row of them reads as different things rather than one thing repeated. */
function art(p, extraClass, style) {
  const inner = p.discipline === 'App'
    ? `<i class="lg"></i><i class="sm"></i><span class="split"><span></span><span></span></span>`
    : `<i class="lg"></i><i class="md"></i><i class="sm"></i><span class="slab"></span>`;
  return `<div class="card__art art-${p.art || 1}${extraClass ? ' ' + extraClass : ''}" aria-hidden="true"${style ? ` style="${style}"` : ''}>
            ${inner}
          </div>`;
}

