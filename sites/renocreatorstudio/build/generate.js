/* ---- case study --------------------------------------------------------- */
function caseStudy(p, i) {
  const next = projects[(i + 1) % projects.length];
  const o = { up: '../', nav: 'work', title: p.title, description: p.summary };

  /* Numbers you can stand behind get the stat band. Nothing to show means a
     spec list instead — a case study with no figures still has to look
     finished rather than like a page with a hole in it. */
  const stats = (p.stats && p.stats.length)
    ? `      <div class="case__stats">
${p.stats.map(s => `        <div class="stat"><b>${esc(s.value)}</b><span>${esc(s.label)}</span></div>`).join('\n')}
      </div>`
    : `      <dl class="spec" style="margin:clamp(2.5rem,6vh,4rem) 0;padding:clamp(2rem,5vh,3rem) 0;border-top:1px solid var(--faint);border-bottom:1px solid var(--faint)">
${(p.spec || []).map(s => `        <div><dt>${esc(s.label)}</dt><dd>${esc(s.value)}</dd></div>`).join('\n')}
      </dl>`;

  const sections = (p.sections || []).map(s => `
      <div class="case__section">
        <div class="case__grid">
          <div><p class="case__label">${esc(s.label)}</p><h2>${esc(s.title)}</h2></div>
          <div class="prose">
${(s.body || []).map(t => `          <p>${t}</p>`).join('\n')}
${s.list && s.list.length ? `            <ul>\n${s.list.map(l => `            <li>${l}</li>`).join('\n')}\n            </ul>` : ''}
${s.quote ? `            <blockquote>${esc(s.quote.text)}<cite>${esc(s.quote.who)}</cite></blockquote>` : ''}
          </div>
        </div>
      </div>`).join('\n');

  return head(o) + nav(o) + `

  <article>
  <section class="scene phero">
    <div class="layer phero__bg" data-depth="0" data-parallax aria-hidden="true"></div>
    <div class="layer" data-depth="1" data-parallax aria-hidden="true"><span class="glow phero__glow"></span></div>

    <div class="inner" data-depth="4" data-fade-group>
      <p class="eyebrow" data-fade><span class="dot"></span>${esc(p.discipline)} · ${esc(p.year)}</p>
      <h1 class="wipe" id="pageTitle" data-wipe="manual">
${p.headline.map(l => `          <span class="line"><span>${l}</span></span>`).join('\n')}
      </h1>
      <p class="lede" data-fade>${p.lede}</p>
      <div class="phero__meta" data-fade>
${(p.meta || []).map(m => `        <span>${esc(m.label)}<b>${esc(m.value)}</b></span>`).join('\n')}
      </div>
    </div>
  </section>

  <section class="scene" style="background:var(--ink-2)">
    <div class="layer" data-depth="0" data-parallax aria-hidden="true" style="background:linear-gradient(180deg,#0A0C10,#0C0E12 60%,#0A0C0F)"></div>
    <div class="layer" data-depth="1" data-parallax aria-hidden="true">
      <span class="glow" style="width:38vw;height:38vw;right:-8%;top:10%;background:rgba(227,183,120,.10)"></span>
    </div>

    <div class="inner" data-depth="4">
      ${art(p, '', 'border:1px solid var(--faint);border-radius:16px;margin-top:clamp(2rem,6vh,4rem)')}

${stats}
${sections}
    </div>
  </section>
  </article>

  <section class="scene next">
    <div class="layer" data-depth="0" data-parallax aria-hidden="true" style="background:linear-gradient(180deg,#0A0C0F,#07080A)"></div>
    <div class="inner" data-depth="4" data-fade-group>
      <p class="eyebrow" data-fade>Next project</p>
      <a class="next__link" href="${next.slug}.html">
        <h2>${esc(next.title)}</h2>
        <span class="card__go">${esc(next.discipline)} <span class="arrow" aria-hidden="true">&rarr;</span></span>
      </a>
      <a class="next__link" href="../contact.html">
        <h2>Start a project</h2>
        <span class="card__go">Tell me what you're making <span class="arrow" aria-hidden="true">&rarr;</span></span>
      </a>
${footer(o)}
    </div>
  </section>
` + tail(o);
}

/* ---- assemble ----------------------------------------------------------- */
function between(html, key, replacement) {
  const re = new RegExp(`<!-- ${key}:START -->[\\s\\S]*?<!-- ${key}:END -->`);
  if (!re.test(html)) throw new Error(`marker ${key} not found`);
  return html.replace(re, `<!-- ${key}:START -->\n${replacement}\n<!-- ${key}:END -->`);
}

function page(name, o, transform) {
  let body = read(`content/pages/${name}.html`)
    .replace(/\{\{AVAILABILITY\}\}/g, esc(site.availability))
    .replace(/\{\{PROJECT_COUNT\}\}/g, String(projects.length).padStart(2, '0'))
    .replace(/\{\{FORM\}\}/g, FORM);
  if (transform) body = transform(body);
  return head(o) + nav(o) + '\n' + body + '\n' + `    <div class="inner" data-depth="4">${footer(o)}\n    </div>\n` + tail(o);
}

const written = [];

/* Home — the footer sits inside the contact section, so it is inlined there
   rather than appended like the other pages. */
{
  const o = { up: '', nav: 'home' };
  let body = read('content/pages/home.html')
    .replace(/\{\{AVAILABILITY\}\}/g, esc(site.availability))
    .replace(/\{\{PROJECT_COUNT\}\}/g, String(projects.length).padStart(2, '0'))
    .replace(/\{\{FORM\}\}/g, FORM);
  body = between(body, 'PROJECT_CARDS',
    projects.length ? projects.map(card).join('\n\n') : EMPTY.replace('../contact', 'contact'));
  body = body.replace('      </div>\n    </div>\n  </section>\n</main>', '');
  body = body.replace(/(\s*<\/div>\s*<\/div>\s*<\/section>\s*)$/, `\n      </div>\n${footer(o)}\n    </div>\n  </section>\n`);
  written.push(write('index.html', head(o) + nav(o) + '\n' + body + tail(o)));
}

/* Work index */
{
  const o = { up: '../', nav: 'work', title: 'Work', description: 'Websites, apps and artwork, designed and made end to end.' };
  written.push(write('work/index.html', page('work', o, b =>
    between(b, 'PROJECT_ROWS', projects.length ? projects.map(row).join('\n\n') : EMPTY))));
}

/* One case study per visible project */
projects.forEach((p, i) => written.push(write(`work/${p.slug}.html`, caseStudy(p, i))));

/* Fixed pages */
written.push(write('process.html', page('process', { up: '', nav: 'process', title: 'Process', description: 'Four phases, the same four every time — brief, direction, make, hand over.' })));
written.push(write('studio.html',  page('studio',  { up: '', nav: 'studio',  title: 'Studio',  description: 'One person, start to finish, no handoffs. Websites, apps and artwork.' })));
written.push(write('contact.html', page('contact', { up: '', nav: 'contact', title: 'Contact', description: 'Tell me what you are making. One project at a time.' })));
written.push(write('404.html',     page('404',     { up: '', nav: '',        title: 'Page not found', description: 'That page does not exist.' })));

/* Remove case study pages whose project was deleted or hidden, so a stale page
   cannot sit there being linked from nothing and indexed by search engines.
   Only files this script wrote are ever touched. */
const keep = new Set(projects.map(p => `${p.slug}.html`).concat(['index.html']));
const pruned = [];
for (const f of fs.readdirSync(path.join(ROOT, 'work'))) {
  if (!f.endsWith('.html') || keep.has(f)) continue;
  const full = path.join(ROOT, 'work', f);
  if (!fs.readFileSync(full, 'utf8').includes('Generated by build/generate.js')) continue;
  fs.unlinkSync(full);
  pruned.push('work/' + f);
}

/* Sitemap and robots */
const today = new Date().toISOString().slice(0, 10);
const urls = ['', 'work/', 'process.html', 'studio.html', 'contact.html']
  .concat(projects.map(p => `work/${p.slug}.html`));
written.push(write('sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  urls.map(u => `  <url>\n    <loc>${site.url}/${u}</loc>\n    <lastmod>${today}</lastmod>\n  </url>`).join('\n') +
  `\n</urlset>\n`));
written.push(write('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${site.url}/sitemap.xml\n`));

console.log(`Built ${written.length} files from ${projects.length} visible project${projects.length === 1 ? '' : 's'}` +
  (all.length - projects.length ? ` (${all.length - projects.length} hidden)` : '') + ':');
written.forEach(f => console.log('  ' + f));
if (pruned.length) {
  console.log(`\nRemoved ${pruned.length} page(s) for hidden or deleted projects:`);
  pruned.forEach(f => console.log('  ' + f));
}

