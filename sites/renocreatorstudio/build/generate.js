/* ==========================================================================
   Builds the site from content/.

     content/site.json     studio name, email, availability
     content/projects.json one object per project — the only file you edit to
                           add, reorder, hide or fill in a project
     content/pages/*.html  the prose of each fixed page

   Everything else is derived: the home gallery, the work index, one case study
   page per visible project, the sitemap. Shared chrome (head, nav, footer,
   enquiry form) lives here so a change lands on every page at once.

   Run:  node build/generate.js
   ========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const read  = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const write = (p, s) => {
  const full = path.join(ROOT, p);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, s);
  return p;
};
const esc = s => String(s).replace(/&(?![a-zA-Z#0-9]+;)/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const site = JSON.parse(read('content/site.json'));
const all  = JSON.parse(read('content/projects.json'));
const projects = all.filter(p => !p.hidden);

